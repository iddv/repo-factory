"""Typed contracts for stored JSON (RCA 2026-10-23, A1; repo-factory-notes plans/CTR-DESIGN.md §2).

**A stored shape is declared once, in code, and crossed only through its type.** Every JSON
column, every ``settings`` key that holds an object and every file repo-factory reads back has one
frozen dataclass deriving from :class:`Stored`:

- **The fields say what a writer may store.** A field any writer may leave null or absent is
  ``X | None = None``; a list or dict a writer may omit is an empty one (``field(
  default_factory=list)``), never ``| None``; a string that is one of a few words is a
  ``Literal`` (``| None`` when an older writer wrote none); a timestamp kept as text is
  :data:`Iso`. Every field has a default, so a row from any older version reads.
- **One parse, total.** :meth:`Stored.parse` and :meth:`Stored.load` never raise: unreadable
  JSON, a non-object, a value of the wrong type all come back as the field's default, and the
  problem is noted once per column and signature (:func:`note`). A numeric string is not a
  number; an int where a float is declared is one; a bool is never a number.
- **One write.** :meth:`Stored.to_json` is what every writer stores (``sort_keys``, a field that
  is None left out: null means absent here, D-10). Keys no field names survive in ``extra``, so
  a rewrite loses nothing a newer version wrote.
- **Readers never see the dict.** The module that owns a table's reads hands out the type.

**For a new writer:** ``null`` means "absent", nothing more. "Not measured", "unknown", "no cap"
are words (a ``Literal``) or a field of their own, never a null a reader has to know about.

The parse is derived from the field types (:func:`_coercer`), so a field added to a type is read,
written, generated odd (:meth:`Stored.odd`) and generated by hypothesis (``stored.testing``) with
no other edit. A type with a shape the derivation cannot say overrides :meth:`Stored.read`.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
import logging
import math
import threading
import types
import typing
from collections.abc import Callable, Iterator, Mapping
from dataclasses import dataclass
from datetime import datetime
from typing import Annotated, Any, ClassVar, Literal, Self, Union, get_args, get_origin

log = logging.getLogger(__name__)


class _IsoMark:
    """The marker in :data:`Iso`'s ``Annotated``."""

    def __repr__(self) -> str:
        return "iso"


ISO = _IsoMark()
#: A timestamp kept as its text (``2026-10-23T16:44:10Z``); one that does not parse reads as None.
Iso = Annotated[str, ISO]

#: The registries, filled as each contract type is defined (``__init_subclass__``):
#: ``(table, column) -> type``, ``settings key -> type`` (a key ending in ``*`` is a prefix),
#: and ``file name -> type``. Importing the package imports every family so they are complete.
COLUMNS: dict[tuple[str, str], type[Stored]] = {}
SETTINGS: dict[str, type[Stored]] = {}
FILES: dict[str, type[Stored]] = {}


@dataclass(frozen=True)
class Problem:
    """One value a parse could not read: where, which key, and what it found instead."""

    where: str  # "sources.validation", "settings:money.halted", "file:activity.json"
    key: str  # the JSON key, dotted for a nested one ("cost_usd.check"); "" the whole
    expected: str  # "float | None", "an object", "JSON"
    got: str  # the type name of what was stored ("str", "list", "NoneType")

    @property
    def signature(self) -> str:
        """Eight hex digits naming the problem, never its value: the same for every row."""
        text = f"{self.where}|{self.key}|{self.expected}|{self.got}"
        return hashlib.sha256(text.encode()).hexdigest()[:8]

    def words(self) -> str:
        what = f"{self.where} {self.key}".strip()
        return f"{what}: expected {self.expected}, found {self.got} (stored-{self.signature})"


_seen_lock = threading.Lock()
_seen: dict[str, Problem] = {}


def note(problem: Problem) -> None:
    """Note a problem once per process and signature: one log line, however many rows have it.
    The row is still read; the field is its default."""
    with _seen_lock:
        if problem.signature in _seen:
            return
        _seen[problem.signature] = problem
    log.warning("stored data not as declared: %s", problem.words())


def problems_seen() -> list[Problem]:
    """Every problem noted in this process, oldest first (for tests and ``repo-factory doctor``)."""
    with _seen_lock:
        return list(_seen.values())


def forget_problems() -> None:
    """Forget the noted problems (tests)."""
    with _seen_lock:
        _seen.clear()


class Noter:
    """Collects what a parse could not read, and notes each once (:func:`note`)."""

    def __init__(self, where: str, prefix: str = "", *, silent: bool = False) -> None:
        self.where = where
        self.prefix = prefix
        self.silent = silent  # a union's trial of one member: kept, not logged
        self.problems: list[Problem] = []

    def child(self, key: str) -> Noter:
        sub = Noter(self.where, f"{self.prefix}{key}.", silent=self.silent)
        sub.problems = self.problems
        return sub

    def bad(self, key: str, expected: str, got: object) -> None:
        p = Problem(self.where, f"{self.prefix}{key}".rstrip("."), expected, type(got).__name__)
        self.problems.append(p)
        if not self.silent:
            note(p)


# -- the coercers --
# A coercer takes a stored value and the Noter and returns (ok, value). Not ok: the caller uses
# the field's default (a list or dict drops the element instead). Each is built once per field
# from the field's type, by _coercer.

Coercer = Callable[[object, Noter, str], tuple[bool, Any]]

_MISSING = object()


def _scalar(kind: type) -> Coercer:
    name = kind.__name__

    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if kind is bool:
            ok = isinstance(v, bool)
        elif kind is int:
            if (
                isinstance(v, float)
                and not isinstance(v, bool)
                and v.is_integer()
                and math.isfinite(v)
            ):
                return True, int(v)
            ok = isinstance(v, int) and not isinstance(v, bool)
        elif kind is float:
            if isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v):
                return True, float(v)
            ok = False
        else:
            ok = isinstance(v, kind)
        if not ok:
            n.bad(key, name, v)
            return False, None
        return True, v

    return c


def _iso(v: object, n: Noter, key: str) -> tuple[bool, Any]:
    if isinstance(v, str):
        try:
            datetime.fromisoformat(v.replace("Z", "+00:00"))
            return True, v
        except ValueError:
            pass
    n.bad(key, "an ISO timestamp", v)
    return False, None


def _any(v: object, n: Noter, key: str) -> tuple[bool, Any]:
    return True, v


def _literal(words: tuple[object, ...]) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if v in words and type(v) in {type(w) for w in words}:
            return True, v
        n.bad(key, "one of " + "|".join(map(str, words)), v)
        return False, None

    return c


def _list(inner: Coercer) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if not isinstance(v, list):
            n.bad(key, "a list", v)
            return False, None
        out = []
        for i, x in enumerate(v):
            ok, y = inner(x, n, f"{key}[{i}]")
            if ok:
                out.append(y)
        return True, out

    return c


def _dict(inner: Coercer) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if not isinstance(v, dict):
            n.bad(key, "an object", v)
            return False, None
        out = {}
        for k, x in v.items():
            ok, y = inner(x, n, f"{key}.{k}")
            if ok:
                out[str(k)] = y
        return True, out

    return c


def _sub(kind: type[Stored]) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if not isinstance(v, dict):
            n.bad(key, f"an object ({kind.__name__})", v)
            return False, None
        return True, kind.read(v, n.child(key))

    return c


def _union(members: list[Coercer], names: str) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        for m in members:
            trial = Noter(n.where, n.prefix, silent=True)  # the members that do not fit: silent
            ok, y = m(v, trial, key)
            if ok:
                for p in trial.problems:  # what did not fit inside the one that does
                    n.problems.append(p)
                    if not n.silent:
                        note(p)
                return True, y
        n.bad(key, names, v)
        return False, None

    return c


def _optional(inner: Coercer) -> Coercer:
    def c(v: object, n: Noter, key: str) -> tuple[bool, Any]:
        if v is None:
            return True, None
        return inner(v, n, key)

    return c


def _is_stored(tp: object) -> typing.TypeGuard[type[Stored]]:
    return isinstance(tp, type) and issubclass(tp, Stored)


def _strip_optional(tp: object) -> tuple[object, bool]:
    """(the type without ``| None``, whether it had it)."""
    if get_origin(tp) in (Union, types.UnionType):
        args = get_args(tp)
        rest = tuple(a for a in args if a is not type(None))
        if len(rest) < len(args):
            if len(rest) == 1:
                return rest[0], True
            return Union[rest], True  # noqa: UP007 (a runtime union of the rest)
    return tp, False


def _coercer(tp: object) -> Coercer:
    """The coercer for a field's declared type."""
    inner, optional = _strip_optional(tp)
    c = _coercer_of(inner)
    return _optional(c) if optional else c


def _coercer_of(tp: object) -> Coercer:
    origin = get_origin(tp)
    if origin is Annotated:
        base, *marks = get_args(tp)
        if any(m is ISO for m in marks):
            return _iso
        return _coercer(base)
    if tp is Any or tp is object:
        return _any
    if _is_stored(tp):
        assert isinstance(tp, type)
        return _sub(tp)
    if tp in (int, float, str, bool):
        assert isinstance(tp, type)
        return _scalar(tp)
    if origin is Literal:
        return _literal(get_args(tp))
    if origin is list:
        (arg,) = get_args(tp) or (Any,)
        return _list(_coercer(arg))
    if origin is dict:
        args = get_args(tp) or (str, Any)
        return _dict(_coercer(args[1]))
    if origin in (Union, types.UnionType):
        members = get_args(tp)
        return _union([_coercer(m) for m in members], " | ".join(_name(m) for m in members))
    raise TypeError(f"a stored field cannot be declared as {tp!r}")


def _name(tp: object) -> str:
    return getattr(tp, "__name__", None) or repr(tp)


# -- the base class --


@dataclass(frozen=True)
class _Field:
    name: str  # the attribute
    key: str  # the JSON key
    tp: object  # the declared type
    coerce: Coercer
    default: Callable[[], Any]


def _default_of(f: dataclasses.Field[Any]) -> Callable[[], Any]:
    if f.default is not dataclasses.MISSING:
        value = f.default
        return lambda: value
    if f.default_factory is not dataclasses.MISSING:
        return f.default_factory
    raise TypeError(
        f"stored field {f.name} has no default: every field needs one, so an "
        "older row (without the key) still reads"
    )


class Stored:
    """The base of every contract type: a frozen dataclass of the stored object's fields.

    Class settings a contract may give:

    ``COLUMN = ("table", "column")``, ``SETTING = "key"`` (``"prefix.*"`` for a family of keys)
    or ``FILE = "name.json"``: where it is stored; registers the type (:data:`COLUMNS`,
    :data:`SETTINGS`, :data:`FILES`).
    ``JSON_NAMES = {"from_text": "from"}``: a field whose JSON key is not its name.
    ``REST = "extra"``: the field that keeps the keys no other field names (``None`` to drop
    them; a contract without such a field drops them).
    ``LIST_ROOT = "items"``: the column holds a JSON list, not an object (``observations.tags``,
    ``ideas.input_ids``): the list is that field, and ``to_json`` writes the list alone.
    """

    COLUMN: ClassVar[tuple[str, str] | None] = None
    SETTING: ClassVar[str | None] = None
    FILE: ClassVar[str | None] = None
    JSON_NAMES: ClassVar[Mapping[str, str]] = {}
    REST: ClassVar[str | None] = "extra"
    LIST_ROOT: ClassVar[str | None] = None

    _fields_cache: ClassVar[tuple[_Field, ...] | None] = None

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        cls._fields_cache = None
        own = cls.__dict__
        if own.get("COLUMN"):
            COLUMNS[own["COLUMN"]] = cls
        if own.get("SETTING"):
            SETTINGS[own["SETTING"]] = cls
        if own.get("FILE"):
            FILES[own["FILE"]] = cls

    # -- where it lives --
    @classmethod
    def where(cls) -> str:
        if cls.COLUMN:
            return ".".join(cls.COLUMN)
        if cls.SETTING:
            return f"settings:{cls.SETTING}"
        if cls.FILE:
            return f"file:{cls.FILE}"
        return cls.__name__

    # -- the fields, derived once --
    @classmethod
    def _fields(cls) -> tuple[_Field, ...]:
        cached = cls.__dict__.get("_fields_cache")
        if cached is not None:
            return typing.cast(tuple[_Field, ...], cached)
        # Derived on first use (two threads may both derive it: the same tuple either way).
        if not dataclasses.is_dataclass(cls):
            raise TypeError(f"{cls.__name__} must be a @dataclass(frozen=True)")
        hints = typing.get_type_hints(cls, include_extras=True)
        out = []
        for f in dataclasses.fields(cls):
            if f.name == cls.REST:
                continue
            out.append(
                _Field(
                    f.name,
                    cls.JSON_NAMES.get(f.name, f.name),
                    hints[f.name],
                    _coercer(hints[f.name]),
                    _default_of(f),
                )
            )
        fields = tuple(out)
        cls._fields_cache = fields
        return fields

    @classmethod
    def _rest(cls) -> str | None:
        if cls.REST and cls.REST in {f.name for f in dataclasses.fields(cls)}:  # type: ignore[arg-type]
            return cls.REST
        return None

    # -- reading --
    @classmethod
    def read(cls, d: Mapping[str, Any], note: Noter) -> Self:
        """The object from a stored dict, every field coerced to its type (a value that is not
        is noted and read as the field's default). Override only for a shape the field types
        cannot say."""
        values: dict[str, Any] = {}
        named = set()
        for f in cls._fields():
            named.add(f.key)
            v = d.get(f.key, _MISSING)
            if v is _MISSING:
                values[f.name] = f.default()
                continue
            ok, got = f.coerce(v, note, f.key)
            if not ok or (got is None and not _accepts_none(f.tp)):
                values[f.name] = f.default()
            else:
                values[f.name] = got
        rest = cls._rest()
        if rest:
            values[rest] = {k: v for k, v in d.items() if k not in named}
        return cls(**values)

    @classmethod
    def from_dict(cls, d: Mapping[str, Any] | None) -> Self:
        """The object from a dict a writer built (or None: the empty object)."""
        if not isinstance(d, Mapping):
            return cls.empty()
        return cls.read(d, Noter(cls.where()))

    @classmethod
    def _decode(
        cls, raw: str | bytes | Mapping[str, Any] | None, n: Noter
    ) -> Mapping[str, Any] | None:
        """The stored value as a dict, or None when it is NULL, empty or unreadable (noted)."""
        if raw is None:
            return None
        if isinstance(raw, Mapping):
            return raw
        if isinstance(raw, (bytes, bytearray)):
            raw = raw.decode("utf-8", "replace")
        if not isinstance(raw, str):
            n.bad("", "JSON text", raw)
            return None
        if not raw.strip():
            return None
        try:
            d = json.loads(raw)
        except ValueError:
            n.bad("", "JSON", raw)
            return None
        if d is None:
            return None
        if isinstance(d, list) and cls.LIST_ROOT:
            return {cls.LIST_ROOT: d}
        if not isinstance(d, dict):
            n.bad("", "a list" if cls.LIST_ROOT else "an object", d)
            return None
        if cls.LIST_ROOT:  # an object where a list is kept
            n.bad("", "a list", d)
            return None
        return d

    @classmethod
    def parse(cls, raw: str | bytes | Mapping[str, Any] | None) -> Self | None:
        """The stored text (or an already-loaded dict) as the type; None when the column is NULL
        or empty, or holds no readable object (noted once). Never raises. For a nullable column
        where NULL means something (a Parallax import's ``sources.validation``)."""
        n = Noter(cls.where())
        d = cls._decode(raw, n)
        if d is None:
            return None
        return cls.read(d, n)

    @classmethod
    def load(cls, raw: str | bytes | Mapping[str, Any] | None) -> Self:
        """As :meth:`parse`, but a NULL, empty or unreadable value is the empty object: for a
        NOT NULL column, or a reader to whom NULL and ``{}`` mean the same."""
        got = cls.parse(raw)
        return got if got is not None else cls.empty()

    @classmethod
    def empty(cls) -> Self:
        """Every field at its default."""
        return cls(
            **{
                f.name: _default_of(f)()
                for f in dataclasses.fields(cls)  # type: ignore[arg-type]
                if f.init
            }
        )

    # -- writing --
    def to_dict(self, *, nulls: bool = False) -> dict[str, Any]:
        """The JSON object: ``extra`` first, the named fields over it; a None field left out
        (what is stored: null means absent), or written as null with ``nulls`` (an API answer
        whose type names every key, nested objects too)."""
        rest = type(self)._rest()
        out: dict[str, Any] = dict(getattr(self, rest)) if rest else {}
        for f in type(self)._fields():
            v = getattr(self, f.name)
            if v is None and not nulls:
                out.pop(f.key, None)
                continue
            out[f.key] = _plain(v, nulls)
        return out

    def to_json(self) -> str:
        """What a writer stores: sorted keys and no spaces (as ``sources.canonical_params``), so
        the same object is the same text (a ``LIST_ROOT`` contract: the list alone)."""
        root = type(self).LIST_ROOT
        value: Any = _plain(getattr(self, root)) if root else self.to_dict()
        return json.dumps(value, sort_keys=True, separators=(",", ":"))

    @classmethod
    def write(cls, d: Mapping[str, Any] | list[Any]) -> str:
        """What a writer that builds a dict (or a list, for a ``LIST_ROOT`` contract) stores:
        the value read through the type and written back. A value the type cannot read is
        noted once, and then the writer's own value is stored as it is: a contract never
        drops what a writer meant to keep (the odd install and the round-trip tests keep the
        types and the writers in step)."""
        n = Noter(cls.where())
        list_root = {cls.LIST_ROOT: d} if cls.LIST_ROOT else None
        raw: Mapping[str, Any] | None = list_root if isinstance(d, list) else d
        if raw is None:
            n.bad("", "an object", d)
            return json.dumps(d, sort_keys=True, separators=(",", ":"), default=str)
        got = cls.read(raw, n)
        if n.problems:
            return json.dumps(d, sort_keys=True, separators=(",", ":"), default=str)
        return got.to_json()

    def api(self) -> dict[str, Any]:
        """The object for an API answer: the keys that are set (no None, no ``extra``)."""
        out = {}
        for f in type(self)._fields():
            v = getattr(self, f.name)
            if v is not None:
                out[f.key] = _plain(v)
        return out

    # -- odd values --
    @classmethod
    def named_odd(cls) -> list[Self]:
        """The odd cases a contract names by hand (the RCA's row, a pack's record): what a real
        writer stores that the derived set (:meth:`odd`) would not make on its own."""
        return []

    @classmethod
    def full(cls) -> Self:
        """Every field set to a value (a sample of its type): the opposite of :meth:`empty`."""
        return cls(**{f.name: _sample(f.tp) for f in cls._fields()})

    @classmethod
    def odd(cls) -> list[Self]:
        """Every odd value the fields allow, derived from the type: the empty object; the full
        one; the full one with each ``| None`` field null, each list and dict empty, each
        ``Literal`` word in turn, each number at 0 and at its largest, each string empty and
        1,000 characters long; and :meth:`named_odd`. A field added is odd with no edit."""
        out: list[Self] = [cls.empty()]
        full = cls.full()
        out.append(full)
        for f in cls._fields():
            for v in _odd_values(f.tp):
                out.append(dataclasses.replace(full, **{f.name: v}))  # type: ignore[type-var]
        out.extend(cls.named_odd())
        return out


def _accepts_none(tp: object) -> bool:
    return _strip_optional(tp)[1] or tp is Any


def _plain(v: Any, nulls: bool = False) -> Any:
    if isinstance(v, Stored):
        return v.to_dict(nulls=nulls)
    if isinstance(v, list):
        return [_plain(x, nulls) for x in v]
    if isinstance(v, dict):
        return {k: _plain(x, nulls) for k, x in v.items()}
    return v


BIG_INT = 2**53 - 1  # the largest integer a JSON reader in a browser keeps exactly
BIG_FLOAT = 1e15
LONG_TEXT = "x" * 1000


def _sample(tp: object) -> Any:
    """A value of the type that is not its default: what :meth:`Stored.full` fills in."""
    inner, _ = _strip_optional(tp)
    origin = get_origin(inner)
    if origin is Annotated:
        base, *marks = get_args(inner)
        if any(m is ISO for m in marks):
            return "2026-01-01T00:00:00Z"
        return _sample(base)
    if _is_stored(inner):
        assert isinstance(inner, type)
        return inner.full()
    if inner is bool:
        return True
    if inner is int:
        return 3
    if inner is float:
        return 0.5
    if inner is str:
        return "odd"
    if origin is Literal:
        return get_args(inner)[0]
    if origin is list:
        (arg,) = get_args(inner) or (Any,)
        return [_sample(arg)]
    if origin is dict:
        args = get_args(inner) or (str, Any)
        return {"k": _sample(args[1])}
    if origin in (Union, types.UnionType):
        return _sample(get_args(inner)[0])
    return "odd"


def _odd_values(tp: object) -> Iterator[Any]:
    inner, optional = _strip_optional(tp)
    if optional:
        yield None
    origin = get_origin(inner)
    if origin is Annotated:
        base, *marks = get_args(inner)
        if any(m is ISO for m in marks):
            return
        yield from _odd_values(base)
        return
    if inner is int:
        yield from (0, BIG_INT)
    elif inner is float:
        yield from (0.0, BIG_FLOAT)
    elif inner is str:
        yield from ("", LONG_TEXT)
    elif origin is Literal:
        yield from get_args(inner)
    elif origin is list:
        yield []
    elif origin is dict:
        yield {}
    elif _is_stored(inner):
        assert isinstance(inner, type)
        yield inner.empty()
