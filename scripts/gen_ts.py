"""Write the web UI's generated TypeScript from the Python side (FE-PLAN §4.1):

- ``src/api/types.gen.ts``: an interface per TypedDict in ``repo_factory/ui/types.py``, the
  ``Routes`` map (``RETURNS``) and ``API_VERSION``;
- ``src/api/actions.gen.ts``: every registry action's kind, its fields' types (from
  ``registry.schema``), its subjects, and the confirm class.

    python3 scripts/gen_ts.py            write both files (run from repo_factory's venv)
    python3 scripts/gen_ts.py --check    exit 1 when either is stale (a test runs this)

Rules: ``list[X]`` -> ``X[]``, ``dict[str, X]`` -> ``Record<string, X>``, ``X | None`` ->
``X | null``, ``Literal`` -> a union, ``NotRequired`` -> ``?``, ``Any`` -> ``unknown``; a type
in ``OPEN`` gains ``[key: string]: unknown``. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
import types
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "repo_factory" / "ui" / "web" / "src" / "api"
HEAD = (
    "// Generated by scripts/gen_ts.py from {src}.\n"
    "// Do not edit: change the Python side and run `python3 scripts/gen_ts.py`;\n"
    "// a test fails when this file is stale.\n"
)


def ts(tp, names: set[str]) -> str:
    """The TypeScript for one Python annotation."""
    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if tp is typing.Any:
        return "unknown"
    if tp is None or tp is type(None):
        return "null"
    if origin is typing.Literal:
        return " | ".join(json.dumps(a) for a in args)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(ts(a, names) for a in args)
    if origin is list:
        inner = ts(args[0], names)
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<string, {ts(args[1], names)}>"
    if typing.is_typeddict(tp):
        if tp.__name__ not in names:
            raise TypeError(f"{tp.__name__} is not defined in repo_factory/ui/types.py")
        return tp.__name__
    simple = {str: "string", int: "number", float: "number", bool: "boolean"}
    if tp in simple:
        return simple[tp]
    raise TypeError(f"gen_ts: no rule for {tp!r}")


def types_ts() -> str:
    from repo_factory.ui import api
    from repo_factory.ui import types as T

    dicts = [v for v in vars(T).values() if typing.is_typeddict(v) and v.__module__ == T.__name__]
    names = {d.__name__ for d in dicts}
    out = [
        HEAD.format(src="repo_factory/ui/types.py"),
        f"export const API_VERSION = {api.API_VERSION};\n",
    ]
    for alias, v in vars(T).items():
        if typing.get_origin(v) is typing.Literal:
            out.append(f"export type {alias} = {ts(v, names)};\n")
    for d in dicts:
        doc = " ".join((d.__doc__ or "").split())
        out.append(f"\n/** {doc} */\n" if doc else "\n")
        out.append(f"export interface {d.__name__} {{\n")
        hints = typing.get_type_hints(d)
        for k, tp in hints.items():
            opt = "" if k in d.__required_keys__ else "?"
            out.append(f"  {k}{opt}: {ts(tp, names)};\n")
        if d.__name__ in T.OPEN:
            out.append("  [key: string]: unknown;\n")
        out.append("}\n")
    out.append("\n/** What each path the page reads answers. */\nexport interface Routes {\n")
    for path, tp in T.RETURNS.items():
        out.append(f"  {json.dumps(path)}: {tp.__name__};\n")
    out.append("}\n")
    return "".join(out)


def schema_ts(s: dict) -> str:
    """The TypeScript for one JSON Schema property of an action's field."""
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(e) for e in s["enum"])
    t = s.get("type")
    if t == "array":
        inner = schema_ts(s.get("items") or {})
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(
        t, "unknown"
    )


def actions_ts() -> str:
    from repo_factory import registry as R

    kinds = sorted(R.ACTIONS)
    out = [
        HEAD.format(src="repo_factory/registry.py (schema)"),
        "export type ActionKind =\n" + "".join(f"  | {json.dumps(k)}\n" for k in kinds) + ";\n\n",
        "/** Each action's fields, as api/act takes them in `fields`. */\n"
        "export interface ActionFields {\n",
    ]
    for k in kinds:
        s = R.schema(k)
        req = set(s.get("required") or [])
        props = {n: p for n, p in s["properties"].items() if n not in ("build", "idea", "confirm")}
        body = "".join(f" {n}{'' if n in req else '?'}: {schema_ts(p)};" for n, p in props.items())
        out.append(
            f"  {json.dumps(k)}: {{{body} }};\n"
            if body
            else f"  {json.dumps(k)}: Record<string, never>;\n"
        )
    out.append(
        "}\n\n/** The actions that run only with `confirm: true`. */\nexport const CONFIRM = [\n"
    )
    out += [f"  {json.dumps(k)},\n" for k in kinds if R.get(k).click == "confirm"]
    out.append(
        "] as const;\nexport type ConfirmKind = (typeof CONFIRM)[number];\n\n"
        "/** What each action can act on. */\n"
        "export const SUBJECTS: Record<ActionKind, readonly string[]> = {\n"
    )
    out += [f"  {json.dumps(k)}: {json.dumps(list(R.get(k).subjects))},\n" for k in kinds]
    out.append("};\n")
    return "".join(out)


FILES = {"types.gen.ts": types_ts, "actions.gen.ts": actions_ts}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a file is stale")
    a = ap.parse_args(argv)
    stale = []
    for name, make in FILES.items():
        text, f = make(), OUT / name
        if f.is_file() and f.read_text() == text:
            continue
        if a.check:
            stale.append(name)
        else:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(text)
            print(f"gen_ts: wrote {f.relative_to(ROOT)}")
    if stale:
        print(f"gen_ts: stale: {', '.join(stale)}; run python3 scripts/gen_ts.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
