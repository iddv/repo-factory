"""The cleanup PR for a product published before repo-factory's exam moved out (EX-PLAN §8.1, PR 6):
repo-factory's scaffolding and documents leave; the adopted suite stays (``--drop-suite`` removes
it); NOTICE names the checks asset; AGENTS.md is written again. No network: the edits only."""

from pathlib import Path

import pytest

from repo_factory.maintain import cleanup

pytestmark = pytest.mark.usefixtures("maintenance_on")

CI = """# ci: install X as the README says and run every suite; scan history for secrets;
# check that AGENTS.md's commands run as written. GitHub-hosted runners only.
name: ci
on: [push]
jobs:
  test:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - name: Unit tests, as the README says
        run: python3 -m unittest discover -s tests -t .
      - name: Acceptance suite
        run: |
          python -m pip install pytest==8.3.3
          python -m pytest tests/acceptance -q

  agents-md:
    runs-on: ubuntu-24.04
    steps:
      - run: python .github/scripts/check_agents_md.py

  gitleaks:
    runs-on: ubuntu-24.04
    steps:
      - run: gitleaks git .
"""
SECURITY = (
    "# Security\n\nHow X was reviewed for security before its first release, what was "
    "found, and what is still open.\n\n## Threat model\n\nA CLI.\n\n## Findings\n\n"
    "| | severity | finding | status |\n|---|---|---|---|\n"
    "| S1 | high | x | fixed (a test checks it) |\n"
    "| S2 | low | Exports are world-readable | open |\n\n"
    "### S2 (low): Exports are world-readable\n\n- Where: x/core.py\n"
    "- Test: `tests/acceptance/test_a.py` (marked as a known open item)\n\n"
    "## Known limits\n\n- Linux only.\n\n"
    "## Reporting a security issue\n\nPlease report security problems privately.\n"
)
NOTICE = (
    "X\n\nCopyright 2026 iddv. See LICENSE.\n\nThis software was generated by an "
    "autonomous software build: a model wrote the code. See SECURITY.md and READINESS.md "
    "for what was checked.\n\nThe idea came from public signals:\n"
)


PROTOCOL = (
    "## Maintenance protocol (issues and labels)\n\n"
    "4. **Reproduce first:** write `tests/acceptance/test_<slug>.py` that fails on `main`"
    " for the\n   reason the issue describes.\n"
    "7. **Documents:** update this file if a command changed; `READINESS.md`\n"
    "   or `SECURITY.md` if a row changed.\n\n## Provenance\n\nSee `READINESS.md`.\n"
)


def repo(tmp_path) -> Path:
    r = tmp_path / "x"
    files = {
        ".github/workflows/ci.yml": CI,
        ".github/scripts/check_agents_md.py": "print()\n",
        ".github/repo-factory.yml": "repo-factory: 1\n",
        "READINESS.md": "# Readiness\n",
        "ASSUMPTIONS.md": "# Assumptions\n",
        "SECURITY.md": SECURITY,
        "NOTICE": NOTICE,
        "AGENTS.md": "# AGENTS.md — X\n\nCI runs these (job `agents-md`).\n\n"
        "- `READINESS.md` is the scorecard.\n- Run `make test`.\n\n" + PROTOCOL,
        "README.md": "# X\n\n## Tests\n\n    make test\n\n## Acceptance tests\n\nEnd-to-end "
        "checks of the product's behaviour are in `tests/acceptance/` (they "
        "need pytest):\n\n    python -m pytest tests/acceptance\n",
        ".github/pull_request_template.md": "- [ ] `READINESS.md` / `SECURITY.md` rows updated if they changed\n",
        "docs/guide.md": "The scorecard is READINESS.md.\n",
        "tests/acceptance/test_a.py": "def test_a(): pass\n",
        "x/core.py": "x = 1\n",
    }
    for rel, text in files.items():
        p = r / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return r


def test_the_scaffolding_and_documents_leave_and_the_suite_stays(tmp_path):
    r = repo(tmp_path)
    seen = []

    def model(prompt):
        seen.append(prompt)
        return (
            "```markdown\n# AGENTS.md — X\n\nRun `make test`; `tests/acceptance/` is ours.\n```",
            0.1,
        )

    done = cleanup.apply(r, model=model, asset="x-0.1.2-checks.tar.gz")
    for gone in (".github/scripts/check_agents_md.py", "READINESS.md", "ASSUMPTIONS.md"):
        assert not (r / gone).exists(), gone
    ci = (r / ".github" / "workflows" / "ci.yml").read_text()
    assert "agents-md" not in ci and "gitleaks" in ci and "check that AGENTS.md" not in ci
    assert ci.startswith(
        "# ci: install X as the README says and run every suite; scan history "
        "for secrets.\n# GitHub-hosted runners only.\nname: ci\n"
    )
    assert "- name: The end-to-end tests" in ci and "pytest tests/acceptance" in ci
    sec = (r / "SECURITY.md").read_text()
    assert "Threat model" not in sec and "Please report security problems privately." in sec
    # a finding still open stays, as a known issue; a fixed one goes with the review
    assert "## Known issues" in sec and "### S2 (low): Exports are world-readable" in sec
    assert "- Where: x/core.py" in sec and "- Test: `tests/acceptance/test_a.py`" in sec
    assert "| S1 |" not in sec and "Linux only" not in sec
    notice = (r / "NOTICE").read_text()
    assert "`x-0.1.2-checks.tar.gz`" in notice and "READINESS.md" not in notice
    assert notice.startswith("X\n\nCopyright 2026 iddv.") and "public signals" in notice
    assert (r / "tests" / "acceptance" / "test_a.py").exists()  # the product's now
    agents = (r / "AGENTS.md").read_text()
    assert agents.startswith("# AGENTS.md — X\n\nRun `make test`")
    # the maintenance protocol carried over (CLAUDE.md points at it), reworded
    assert "## Maintenance protocol (issues and labels)" in agents
    assert "write a test in the product's own suite (see the tests above) that fails" in agents
    assert "`SECURITY.md` if a known issue changed" in agents and "READINESS" not in agents
    assert "## Provenance" not in agents
    assert "README.md" in seen[0] and "x/core.py" in seen[0]
    assert len(done) == 8 and (r / ".github" / "repo-factory.yml").exists()
    assert (
        r / ".github" / "pull_request_template.md"
    ).read_text() == "- [ ] `SECURITY.md`'s known issues updated if they changed\n"
    left = cleanup.leftovers(r)
    assert left == ["`docs/guide.md` line 1 still names `READINESS.md`"]
    body = cleanup.pr_body("iddv/x", done, "x-0.1.2-checks.tar.gz", None, "v0.1.2", False, left)
    assert "gh release upload v0.1.2" in body and "stays" in body
    assert "**Left for you**" in body and "`docs/guide.md` line 1" in body


def test_drop_suite_removes_it_its_ci_step_and_its_readme_section(tmp_path):
    r = repo(tmp_path)
    cleanup.apply(r, drop_suite=True)
    assert not (r / "tests" / "acceptance").exists()
    ci = (r / ".github" / "workflows" / "ci.yml").read_text()
    assert "tests/acceptance" not in ci and "Unit tests, as the README says" in ci
    assert "Acceptance tests" not in (r / "README.md").read_text()
    sec = (r / "SECURITY.md").read_text()
    assert "### S2 (low)" in sec and "- Test:" not in sec  # its test went with the suite
    agents = (r / "AGENTS.md").read_text()  # the fallback, no model
    assert "agents-md" not in agents and "READINESS.md" not in agents and "make test" in agents
    assert "`SECURITY.md` if a known issue changed" in agents and "own suite" in agents
    assert "## Provenance" not in agents


def test_a_second_dry_run_finds_the_same_changes(tmp_path):
    import subprocess

    src = repo(tmp_path)
    for args in (
        ["init", "-q", "-b", "main"],
        ["add", "-A"],
        ["-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-q", "-m", "v1"],
    ):
        subprocess.run(["git", *args], cwd=src, check=True)

    def gh(*args, check=True):
        if args[:2] == ("repo", "clone"):
            subprocess.run(["git", "clone", "-q", str(src), args[3]], check=True)
            return ""
        if args[:2] == ("release", "list"):
            return "v0.1.2\n"
        raise AssertionError(args)

    work = tmp_path / "work" / "x"
    first = cleanup.cleanup(gh, "iddv/x", work, dry_run=True, log=lambda m: None)
    again = cleanup.cleanup(gh, "iddv/x", work, dry_run=True, log=lambda m: None)
    assert first["done"] and again["done"] == first["done"]
    assert again["pr"] is None and "READINESS.md" in again["diff"]


def test_a_product_with_none_of_it_has_nothing_to_clean(tmp_path):
    r = tmp_path / "y"
    (r / "x").mkdir(parents=True)
    (r / "README.md").write_text("# Y\n")
    (r / "SECURITY.md").write_text("# Security\n\nReport privately.\n")
    assert cleanup.apply(r) == []
